#!/usr/bin/env python3
"""Regenerates icon assets from the OSHD icon pack.
usage: python3 scripts/gen-icons.py "/path/to/OSHD - Icons"
Outputs: src/shared/icon-index.ts, src/icon-data.ts, docs/icons/*.png"""
import sys, os, re, base64, io, json
from PIL import Image
src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.makedirs(f"{root}/docs/icons", exist_ok=True)
items = []
for dp, _, fs in os.walk(src):
    for f in fs:
        if not f.lower().endswith(".png"): continue
        stem = re.sub(r"^OSHD-+", "", f[:-4])
        m = re.match(r"(.+)-(\d+)$", stem)
        name, num = m.group(1), int(m.group(2))
        rel = os.path.relpath(dp, src).split(os.sep)
        cat = rel[0].replace("OSHD - ", "") if rel[0] != "." else name
        iid = f"{name.lower()}-{num:02d}"
        label = f"{name.replace('-', ' ')} {num}"
        items.append((cat, iid, label, os.path.join(dp, f)))
items.sort(key=lambda t: (t[0], t[1]))
data = {}
for cat, iid, label, path in items:
    im = Image.open(path).convert("RGBA").resize((128, 128), Image.LANCZOS)
    im.save(f"{root}/docs/icons/{iid}.png", optimize=True)
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    data[iid] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
idx = [{"id": i, "category": c, "label": l} for c, i, l, _ in items]
with open(f"{root}/src/shared/icon-index.ts", "w") as f:
    f.write("// Generated by scripts/gen-icons.py\nexport interface IconDef { id: string; category: string; label: string }\n")
    f.write("export const ICON_INDEX: IconDef[] = " + json.dumps(idx, indent=1) + ";\n")
with open(f"{root}/src/icon-data.ts", "w") as f:
    f.write("// Generated by scripts/gen-icons.py (plugin-only: icons are inlined so main.js is self-contained)\n")
    f.write("export const ICON_DATA: Record<string, string> = " + json.dumps(data) + ";\n")
print(len(items), "icons")
